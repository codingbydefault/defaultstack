import assert from 'node:assert/strict';
import {repositoryAppManifest,validSetupState,privateAppConfig} from '../../src/lib/github/setup.mjs';
import {isPlatformOwner} from '../../src/lib/auth/owner.mjs';
const manifest=repositoryAppManifest();
assert.deepEqual(manifest.default_permissions,{contents:'read',metadata:'read'});
assert.equal(manifest.public,false);
assert.equal(manifest.callback_urls[0],'https://defaultstackr.cloud/api/github/callback');
assert.equal(manifest.request_oauth_on_install,false);
const state='a'.repeat(64);
assert(validSetupState(state,state));
for(const incoming of [null,'',state.slice(1),'b'.repeat(64)])assert.equal(validSetupState(incoming,state),false);
const app={owner:{login:'codingbydefault'},client_id:'Iv1_fixture',client_secret:'fixture-only-secret',slug:'owner-repositories',permissions:{contents:'read'}};
assert.equal(privateAppConfig(app).appSlug,'owner-repositories');
assert.equal(privateAppConfig({...app,owner:{login:'someone-else'}}),null);
assert.equal(privateAppConfig({...app,permissions:{contents:'write'}}),null);
assert.equal(privateAppConfig({...app,client_secret:''}),null);
assert(isPlatformOwner('owner-id','owner-id'));
for(const id of [null,'','other','OWNER-ID'])assert.equal(isPlatformOwner(id,'owner-id'),false);
console.log('PASS: read-only repository manifest, owner binding, state mismatch rejection and private configuration validation');
